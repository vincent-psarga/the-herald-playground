/**
 * The beast entire: its claws and its tongue are part of it.
 *
 * A lion has claws whether or not a blazon says anything about them, and armed
 * says what colour they are drawn rather than that there are any. So they are
 * drawn with the rest of the beast and in the beast's own tincture, and an
 * attribute paints over them — which is the difference between a part a figure
 * has and a part a name gives it, the ring having no stone until something says
 * there is one.
 *
 * One path of several pieces, as the lily is, so that the tincture fills the
 * whole of it at once and no line is left where a claw meets its paw.
 */
const RAMPANT = BODY + CLAWS + TONGUE;

/** A lion rampant about a centre, drawn that many units tall. */
export const lion = (x: number, y: number, size: number): Shape => placed(RAMPANT, x, y, size);

/** Its claws alone, to be laid over it in the tincture it is armed with. */
export const lionClaws = (x: number, y: number, size: number): Shape => placed(CLAWS, x, y, size);

/** Its tongue alone, to be laid over it in the tincture it is langued with. */
export const lionTongue = (x: number, y: number, size: number): Shape => placed(TONGUE, x, y, size);

/** The marks it is modelled by, to be washed over it in no tincture at all. */
export const lionModelling = (x: number, y: number, size: number): Shape =>
  placed(MODELLING, x, y, size);
