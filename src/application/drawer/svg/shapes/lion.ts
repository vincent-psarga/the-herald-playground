/*
 * The lion, traced from the arms of Gallegantin le Gallois in the armorial of
 * the Knights of the Round Table — Bibliothèque nationale de France, ms. fr.
 * 12597, folio 62 recto, which blazons them "parti d'or et de sable a ung lyon
 * de sinople arme et langue de gueulles".
 *
 * Traced and not drawn. A lily can be written out in a dozen numbers that say
 * what they mean; a beast cannot, and a beast invented here would be this
 * library's opinion about what a lion looks like. So the painter's own outline
 * is what is kept: the green of the beast was cut from the folio, the hatching
 * over it closed up, the boundary followed and thinned until a hundred points
 * were left, and the run of them written as curves. The claws and the tongue
 * were cut the same way out of the red, and the modelling out of the darker of
 * the two greens the beast is painted in.
 *
 * Turned upright by half a right angle. The folio hangs its shield tilted, as a
 * shield hangs from a helm, and the beast is painted square to the shield
 * rather than to the page — so the outline came off the page leaning, and what
 * is wanted is the lion as an upright shield bears it: standing on its hind
 * paws with its head to the chief.
 *
 * Which is why the numbers below cannot be argued with one by one. What can be
 * argued with is the figure they draw, and the folio is beside it.
 *
 * The beast is rampant, which is the posture a blazon that names none means:
 * "le Lion dans sa position naturelle est rampant ... ne posant que sur ses
 * pattes de derrière, la tête de profil, la queue retroussée vers le dos avec
 * la houppe retombant en dehors".
 *
 * Four figures and not one, because three of them are painted apart from the
 * rest: the beast, the claws it is armed with, the tongue it is langued with,
 * and the marks it is modelled by. All four are written about one centre in the
 * same box, so that laying one over another puts the claws on the paws, the
 * tongue in the mouth and the shading where the painter shaded.
 */

